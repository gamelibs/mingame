function migrate(behaviors: Behavior[]): Behavior[] {
  return behaviors.map((b) => ({ ...b, category: mapCategory(b) }));
}

function serializeBehavior(b: Behavior): string {
  const obj: Record<string, unknown> = { ...b };
  if (obj.narrative === undefined) delete obj.narrative;
  const json = JSON.stringify(obj, null, 2);
  // 缩进两级，与文件格式一致
  return json
    .split('\n')
    .map((line) => '  ' + line)
    .join('\n');
}

function writeBehaviorsFile(filePath: string, exportName: string, behaviors: Behavior[]): void {
  const header = `import { Behavior } from '../types';\n\nexport const ${exportName}: Behavior[] = [\n`;
  const body = behaviors.map((b) => serializeBehavior(b)).join(',\n');
  const footer = '\n];\n';
  fs.writeFileSync(filePath, header + body + footer, 'utf8');
}

